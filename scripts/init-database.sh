#!/bin/sh
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=app_password="$APP_DB_PASSWORD" <<'SQL'
CREATE ROLE lms_app LOGIN PASSWORD :'app_password';
GRANT CONNECT ON DATABASE lms TO lms_app;
GRANT USAGE ON SCHEMA public TO lms_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO lms_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO lms_app;
CREATE DATABASE lms_test;
SQL
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname lms_test <<'SQL'
GRANT CONNECT ON DATABASE lms_test TO lms_app;
GRANT USAGE ON SCHEMA public TO lms_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO lms_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO lms_app;
SQL
